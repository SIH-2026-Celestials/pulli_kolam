"""M4.3 Phase 1: train V3-A. Reuses DotHeatmapNetV2 architecture
UNCHANGED (per the task's explicit "do not increase model size"
instruction) -- only the training DATA changes (experiments/m4_3/data/,
generated by generate_training_data_v3.py). Same distribution-matching
discipline as experiments/m4_2/train.py: trains on
engine.image_io.preprocess(path).binary, not the raw photo. CPU-only,
deterministic seed.

Difference from experiments/m4_2/train.py's dataset loader: handles
images with ZERO ground-truth dots (the new negative/no-pattern samples)
-- cv2.transform/reshape on an empty point array needs an explicit guard,
the M4.2 loader never needed one because M4.2's dataset had no negatives.
"""
from __future__ import annotations

import glob
import json
import os
import sys
import time

import cv2
import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from experiments.m4_2.model import DotHeatmapNetV2, MODEL_INPUT_SIZE, OUTPUT_STRIDE, HEATMAP_SIZE, make_gaussian_heatmap  # noqa: E402
from engine import image_io  # noqa: E402

DATA_DIR = os.path.join(os.path.dirname(__file__), "data")
CKPT_DIR = os.path.join(os.path.dirname(__file__), "checkpoints")
RESULTS_DIR = os.path.join(os.path.dirname(__file__), "results")
BEST_CKPT = os.path.join(CKPT_DIR, "v3a_best.pt")
FINAL_CKPT = os.path.join(CKPT_DIR, "v3a_final.pt")

SEED = 42


class DotHeatmapDatasetV3(Dataset):
    def __init__(self, split_dir: str):
        self.samples = []
        json_paths = sorted(glob.glob(os.path.join(split_dir, "*.json")))
        for json_path in json_paths:
            with open(json_path) as f:
                gt = json.load(f)

            preprocessed = image_io.preprocess(gt["image_path"])
            binary = preprocessed.binary
            h, w = binary.shape

            gt_px_raw = list(gt["dot_pixel_positions"].values())
            if gt_px_raw:
                img = cv2.imread(gt["image_path"])
                M = cv2.getRotationMatrix2D((w / 2, h / 2), preprocessed.rotation_deg, 1.0)
                gt_px = np.array(gt_px_raw, dtype=np.float32)
                deskewed_gt_px = cv2.transform(gt_px.reshape(-1, 1, 2), M).reshape(-1, 2)
            else:
                deskewed_gt_px = np.zeros((0, 2), dtype=np.float32)

            resized = cv2.resize(binary, (MODEL_INPUT_SIZE, MODEL_INPUT_SIZE), interpolation=cv2.INTER_AREA)
            img_t = torch.from_numpy(resized.astype(np.float32) / 255.0).unsqueeze(0)

            fx, fy = MODEL_INPUT_SIZE / w, MODEL_INPUT_SIZE / h
            dot_positions_heatmap_space = [
                (px * fx / OUTPUT_STRIDE, py * fy / OUTPUT_STRIDE) for (px, py) in deskewed_gt_px
            ]
            heatmap = make_gaussian_heatmap(dot_positions_heatmap_space, HEATMAP_SIZE, HEATMAP_SIZE)
            self.samples.append((img_t, heatmap.unsqueeze(0)))

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        return self.samples[idx]


def run_epoch(model, loader, optimizer, loss_fn, train: bool) -> float:
    model.train(train)
    total_loss = 0.0
    n = 0
    for img, target in loader:
        if train:
            optimizer.zero_grad()
        logits = model(img)
        loss = loss_fn(logits, target)
        if train:
            loss.backward()
            optimizer.step()
        total_loss += loss.item() * img.shape[0]
        n += img.shape[0]
    return total_loss / n


def main(n_epochs: int = 18, lr: float = 1e-3, batch_size: int = 8):
    """n_epochs default reduced from M4.2's 30 -- Phase 10 time-management
    instruction: reduce epochs if training is slow, evaluate the best
    checkpoint immediately rather than waiting for full convergence. Seed
    stays deterministic regardless of epoch count."""
    torch.manual_seed(SEED)
    t_start = time.monotonic()

    print("Loading V3-A train set (running preprocess() on every image)...")
    train_ds = DotHeatmapDatasetV3(os.path.join(DATA_DIR, "train"))
    print("Loading V3-A val set...")
    val_ds = DotHeatmapDatasetV3(os.path.join(DATA_DIR, "val"))
    print(f"train images: {len(train_ds)}, val images: {len(val_ds)}")
    t_data = time.monotonic()

    train_loader = DataLoader(train_ds, batch_size=batch_size, shuffle=True)
    val_loader = DataLoader(val_ds, batch_size=batch_size, shuffle=False)

    model = DotHeatmapNetV2()
    print(f"model parameters: {model.n_parameters()} (architecture unchanged from V2)")

    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    loss_fn = nn.BCEWithLogitsLoss()

    best_val_loss = float("inf")
    history = []
    for epoch in range(n_epochs):
        train_loss = run_epoch(model, train_loader, optimizer, loss_fn, train=True)
        with torch.no_grad():
            val_loss = run_epoch(model, val_loader, optimizer, loss_fn, train=False)
        history.append({"epoch": epoch, "train_loss": train_loss, "val_loss": val_loss})
        print(f"epoch {epoch:3d}  train_loss={train_loss:.4f}  val_loss={val_loss:.4f}  "
              f"elapsed={time.monotonic() - t_start:.0f}s")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            os.makedirs(CKPT_DIR, exist_ok=True)
            torch.save(model.state_dict(), BEST_CKPT)

    os.makedirs(CKPT_DIR, exist_ok=True)
    torch.save(model.state_dict(), FINAL_CKPT)

    t_end = time.monotonic()
    log = {
        "n_epochs": n_epochs, "lr": lr, "batch_size": batch_size, "seed": SEED,
        "model_parameters": model.n_parameters(), "best_val_loss": best_val_loss,
        "n_train_images": len(train_ds), "n_val_images": len(val_ds),
        "data_loading_seconds": t_data - t_start, "training_seconds": t_end - t_data,
        "total_seconds": t_end - t_start,
        "history": history,
        "checkpoints": {"best": BEST_CKPT, "final": FINAL_CKPT},
    }
    os.makedirs(RESULTS_DIR, exist_ok=True)
    with open(os.path.join(RESULTS_DIR, "v3a_training_log.json"), "w") as f:
        json.dump(log, f, indent=2)

    print(f"\nBest val_loss: {best_val_loss:.4f}")
    print(f"Total time: {t_end - t_start:.0f}s (data load {t_data - t_start:.0f}s, train {t_end - t_data:.0f}s)")
    print(f"Checkpoints: {BEST_CKPT}, {FINAL_CKPT}")


if __name__ == "__main__":
    import sys as _sys
    n_ep = int(_sys.argv[1]) if len(_sys.argv) > 1 else 18
    main(n_epochs=n_ep)
